DEFAULT_SOUNDS = {"tada": "done", "hm": "needs-input"}


def read_catalog() -> list[tuple[str, str, str]]:
    if not CATALOG_PATH.exists():
        raise FileNotFoundError(f"{CATALOG_PATH} is missing; run tools/make-sounds.py first")
    entries = []
    for line_number, line in enumerate(CATALOG_PATH.read_text(encoding="utf-8").splitlines(), start=1):
        fields = line.split("\t")
        if len(fields) != 3:
            raise ValueError(f"{CATALOG_PATH}:{line_number}: expected name, kind, description separated by tabs")
        entries.append((fields[0], fields[1], fields[2]))
    return entries


def render_card(name: str, kind: str, description: str) -> str:
    event_name = "done" if kind == "done" else "needs-input"
    default_tag = f'<span class="tag">default for {DEFAULT_SOUNDS[name]}</span>' if name in DEFAULT_SOUNDS else ""
    return (
        f'    <button class="card" data-sound={json.dumps(name)}>'
        f'<span class="play-icon" aria-hidden="true">&#9654;</span>'
        f"<span><span class=\"card-name\">{html.escape(name)}{default_tag}</span>"
        f'<span class="card-description">{html.escape(description)}</span>'
        f'<span class="card-command">/tada:sound {event_name} {html.escape(name)}</span></span></button>'
    )


def render_sections(entries: list[tuple[str, str, str]]) -> str:
    sections = []
    for kind, (heading, note) in KIND_HEADINGS.items():
        cards = [render_card(name, entry_kind, description) for name, entry_kind, description in entries if entry_kind == kind]
        sections.append(
            f"  <h2>{heading}</h2>\n  <p class=\"section-note\">{note}</p>\n"
            f'  <div class="grid">\n' + "\n".join(cards) + "\n  </div>"
        )
    return "\n".join(sections)


def main() -> None:
    entries = read_catalog()
    page = PAGE_TEMPLATE.replace("__COUNT__", str(len(entries))).replace("__SECTIONS__", render_sections(entries))
    OUTPUT_PATH.parent.mkdir(exist_ok=True)
    OUTPUT_PATH.write_text(page, encoding="utf-8", newline="\n")
    print(f"wrote {OUTPUT_PATH} with {len(entries)} sounds")


if __name__ == "__main__":
    main()
